"""Human-invoked CLI for native sync and searchable FiveM reference data."""
from __future__ import annotations
import argparse
import json
from . import natives, events, animations, catalogs, intelligence, profiler, ast_analysis, devbridge, controlbridge, livecontrol, clientlaunch, gameinput, fxserverlaunch

def main():
    parser=argparse.ArgumentParser(prog='cfx-devkit',description='FiveM-only native and event reference')
    sub=parser.add_subparsers(dest='command',required=True)
    sub.add_parser('native-status')
    sub.add_parser('sync-natives',help='Requires CFX_ENABLE_NETWORK=1; caches official GTA5 and CFX native JSON.')
    native=sub.add_parser('search-native')
    native.add_argument('query')
    native.add_argument('--source',choices=['all','gta5','cfx'],default='all')
    native.add_argument('--limit',type=int,default=10)
    ev=sub.add_parser('search-event')
    ev.add_argument('query')
    sub.add_parser('animation-status',help='Report available GTA V animation dataset size, provenance and completeness')
    sub.add_parser('sync-animations',help='Download the full GTA V dump; requires CFX_ENABLE_NETWORK=1')
    anim=sub.add_parser('search-animation-dict')
    anim.add_argument('query',nargs='?',default='')
    anim.add_argument('--offset',type=int,default=0)
    anim.add_argument('--limit',type=int,default=25)
    clips=sub.add_parser('search-animation-clip')
    clips.add_argument('query')
    clips.add_argument('--dictionary',default='')
    clips.add_argument('--offset',type=int,default=0)
    clips.add_argument('--limit',type=int,default=25)
    details=sub.add_parser('animation-detail')
    details.add_argument('dictionary')
    details.add_argument('--offset',type=int,default=0)
    details.add_argument('--limit',type=int,default=50)
    pair=sub.add_parser('validate-animation')
    pair.add_argument('dictionary')
    pair.add_argument('clip')
    lua=sub.add_parser('animation-lua')
    lua.add_argument('dictionary')
    lua.add_argument('clip')
    lua.add_argument('--flag',type=int,default=49)
    lua.add_argument('--duration',type=int,default=-1)
    sub.add_parser('animation-prefixes')
    sub.add_parser('asset-status')
    asset_sync=sub.add_parser('sync-assets',help='Download one GTA V asset catalog into local cache, opt-in network')
    asset_sync.add_argument('catalog',choices=list(catalogs.CATALOGS))
    asset_search=sub.add_parser('search-assets')
    asset_search.add_argument('catalog',choices=list(catalogs.CATALOGS))
    asset_search.add_argument('query',nargs='?',default='')
    asset_search.add_argument('--offset',type=int,default=0)
    asset_search.add_argument('--limit',type=int,default=25)
    asset_search.add_argument('--clips',action='store_true')
    sub.add_parser('index-project',help='Print static Lua event/command indexes')
    sub.add_parser('audit-authority',help='Static security review leads (not guarantees)')
    sub.add_parser('audit-streaming',help='Report missing fxmanifest asset references')
    trace=sub.add_parser('profile-trace',help='Summarize a Chrome Trace JSON captured from a development profiler')
    trace.add_argument('path')
    trace.add_argument('--limit',type=int,default=20)
    sub.add_parser('ast-status',help='Check optional Lua tree-sitter AST parser')
    ast=sub.add_parser('ast-index',help='Parse Lua calls using a real AST')
    ast.add_argument('--project',default='.')
    audits=sub.add_parser('ast-network-review',help='AST-confirmed network registrations needing manual review')
    audits.add_argument('--project',default='.')
    bridge=sub.add_parser('dev-bridge',help='Start the opt-in 127.0.0.1-only reporter receiver')
    bridge.add_argument('--port',type=int,default=8765)
    recent=sub.add_parser('bridge-recent',help='Read sanitized resource-only diagnostic events')
    recent.add_argument('--limit',type=int,default=50)
    recent.add_argument('--resource',default='')
    control=sub.add_parser('control-broker',help='Run opt-in development-only resource lifecycle broker (127.0.0.1)')
    control.add_argument('--port',type=int,default=controlbridge.PORT)
    state=sub.add_parser('control-status',help='Inspect local proposal statuses, never exec')
    state.add_argument('request_id',nargs='?',default=None)
    appr=sub.add_parser('control-approve',help='Require human to confirm an allowlisted resource action')
    appr.add_argument('request_id')
    deny=sub.add_parser('control-reject',help='Require human to deny pending action')
    deny.add_argument('request_id')
    live=sub.add_parser('live-broker',help='Start loopback-only full FiveM dev control bridge')
    live.add_argument('--port',type=int,default=livecontrol.PORT)
    arm=sub.add_parser('live-arm',help='ARM full client/server game control from a human terminal ONLY')
    arm.add_argument('--minutes',type=int,default=15)
    sub.add_parser('live-disarm',help='Emergency disarm: cancel queued game requests')
    sub.add_parser('live-status',help='See armed state and observed FXServer polling')
    request=sub.add_parser('live-result')
    request.add_argument('id')
    send=sub.add_parser('live-run',help='Submit dev-only game operation after interactive arming')
    send.add_argument('kind',choices=sorted(livecontrol.KINDS))
    send.add_argument('--payload',default='{}')
    send.add_argument('--target',type=int,default=0)
    log=sub.add_parser('live-log',help='Read configured local dev server/client log while armed')
    log.add_argument('--channel',choices=['server','client'],default='server')
    log.add_argument('--lines',type=int,default=60)
    log.add_argument('--contains',default='')
    la=sub.add_parser('client-launch-arm',help='Human-only permission to start FiveM and join localhost')
    la.add_argument('--port',type=int,default=30120)
    la.add_argument('--minutes',type=int,default=15)
    sub.add_parser('client-launch-disarm',help='Revoke FiveM launch permission')
    sub.add_parser('client-launch-status',help='Read current launch-only permission')
    ia=sub.add_parser('game-input-arm',help='Human-only approval for foreground FiveM input')
    ia.add_argument('--minutes',type=int,default=15)
    sub.add_parser('game-input-disarm',help='Revoke all FiveM input permission')
    sub.add_parser('game-input-status',help='Inspect permission and foreground process')
    fa=sub.add_parser('fxserver-arm',help='Human-only authorization for local FXServer startup')
    fa.add_argument('--port',type=int,default=30120)
    fa.add_argument('--minutes',type=int,default=15)
    sub.add_parser('fxserver-disarm',help='Revoke FXServer startup permission')
    sub.add_parser('fxserver-status',help='Discover workspace FXServer installations and inspect startup approval/readiness')
    connect=sub.add_parser('connect',help='Select the local server, request missing terminal approvals, then connect FiveM immediately')
    connect.add_argument('--port',type=int,default=30120)
    connect.add_argument('--minutes',type=int,default=15)
    args=parser.parse_args()
    try:
        if args.command=='connect':result=fxserverlaunch.connect(args.port,args.minutes)
        elif args.command=='fxserver-arm':result=fxserverlaunch.arm(args.port,args.minutes)
        elif args.command=='fxserver-disarm':result=fxserverlaunch.disarm()
        elif args.command=='fxserver-status':result=fxserverlaunch.status()
        elif args.command=='game-input-arm':result=gameinput.arm(args.minutes)
        elif args.command=='game-input-disarm':result=gameinput.disarm()
        elif args.command=='game-input-status':result=gameinput.status()
        elif args.command=='native-status':result=natives.index_status()
        elif args.command=='sync-natives':result=natives.sync_natives()
        elif args.command=='search-native':result=natives.find_natives(args.query,args.source,limit=args.limit)
        elif args.command=='search-event':result=events.search_events(args.query)
        elif args.command=='ast-status':result=ast_analysis.available()
        elif args.command=='ast-index':result=ast_analysis.analyze_project(args.project)
        elif args.command=='ast-network-review':result=ast_analysis.audit_network_handlers(args.project)
        elif args.command=='bridge-recent':result=devbridge.read_events(args.limit,args.resource)
        elif args.command=='client-launch-arm':result=clientlaunch.arm(args.port,args.minutes)
        elif args.command=='client-launch-disarm':result=clientlaunch.disarm()
        elif args.command=='client-launch-status':result=clientlaunch.permission()
        elif args.command=='live-broker':return livecontrol.serve(args.port)
        elif args.command=='live-arm':result=livecontrol.arm(args.minutes)
        elif args.command=='live-disarm':result=livecontrol.disarm()
        elif args.command=='live-status':result=livecontrol.status()
        elif args.command=='live-result':result=livecontrol.status(args.id)
        elif args.command=='live-run':result=livecontrol.submit(args.kind,args.payload,args.target)
        elif args.command=='live-log':result=livecontrol.tail_log(args.channel,args.lines,args.contains)
        elif args.command=='control-broker':return controlbridge.serve(args.port)
        elif args.command=='control-status':result=controlbridge.status(args.request_id)
        elif args.command=='control-approve':result=controlbridge.review_cli(args.request_id,True)
        elif args.command=='control-reject':result=controlbridge.review_cli(args.request_id,False)
        elif args.command=='dev-bridge':return devbridge.serve(args.port)
        elif args.command=='profile-trace':result=profiler.summarize_trace(args.path,args.limit)
        elif args.command=='asset-status':result=catalogs.status()
        elif args.command=='sync-assets':result=catalogs.sync(args.catalog)
        elif args.command=='search-assets':result=catalogs.search(args.catalog,args.query,args.offset,args.limit,args.clips)
        elif args.command=='index-project':result=intelligence.workspace_index()
        elif args.command=='audit-authority':result=intelligence.authority_review()
        elif args.command=='audit-streaming':result=intelligence.manifest_asset_report()
        elif args.command=='animation-status':result=animations.status()
        elif args.command=='sync-animations':result=animations.sync_animations()
        elif args.command=='search-animation-dict':result=animations.search_dictionaries(args.query,args.offset,args.limit)
        elif args.command=='search-animation-clip':result=animations.search_clips(args.query,args.dictionary,args.offset,args.limit)
        elif args.command=='animation-detail':result=animations.dictionary_details(args.dictionary,args.offset,args.limit)
        elif args.command=='validate-animation':result=animations.validate_pair(args.dictionary,args.clip)
        elif args.command=='animation-lua':result=animations.generate_lua(args.dictionary,args.clip,args.flag,args.duration)
        elif args.command=='animation-prefixes':result=animations.prefix_counts()
        else:parser.error('Unknown command')
    except (ValueError,OSError) as exc:
        parser.exit(2,f'Error: {exc}\n')
    print(json.dumps(result,indent=2,ensure_ascii=False))

if __name__=='__main__':main()
